# Journal-ready reproducibility supplement bundler (zip-slip & confinement safe)

# Build peer-review README_REPRODUCE.md guide for an exported capsule bundle
build_reproduce_readme <- function(manifest, verification = NULL, platform = NULL, included_files = character()) {
  proj <- manifest$project$name %||% "capsule"
  ep <- manifest$project$entrypoint %||% "<entrypoint>"
  r_ver <- manifest$environment$r_version %||% current_r_version()
  seed_lbl <- if (!is.null(manifest$rng$seed)) as.character(manifest$rng$seed) else "unset"
  tcs <- unlist(manifest$environment$toolchains)
  tc_str <- if (length(tcs) > 0L) paste(tcs, collapse = ", ") else "Standard R"
  plat_flag <- if (!is.null(platform)) paste0("--platform=", platform, " ") else ""

  ver_lines <- if (!is.null(verification)) {
    c(
      paste0("- **Verification Status:** `", status_label(verification$status), "`"),
      paste0("- **Verified At:** `", verification$verified_at, "` via `", verification$runner, "` runner (", verification$duration_sec, "s)"),
      paste0("- **Outputs Verified:** ", sum(verification$output_checks$passed), " / ", nrow(verification$output_checks))
    )
  } else {
    c("- **Verification Status:** Not executed at bundle export time (run Step 1 below to audit).")
  }

  c(
    paste0("# Reproducibility Supplement: ", sanitize_markdown_inline(proj)),
    "",
    "This archive is a self-contained reproducibility capsule generated by **`rcapsule`**.",
    "",
    "## Provenance Summary",
    "",
    paste0("- **Capsule ID:** `", sanitize_markdown_inline(manifest$capsule_id), "`"),
    paste0("- **Schema Version:** `", sanitize_markdown_inline(manifest$schema_version), "`"),
    paste0("- **Content Digest (SHA-256):** `", sanitize_markdown_inline(manifest$integrity$content_digest), "`"),
    paste0("- **HMAC-SHA256 Signed:** `", isTRUE(manifest$integrity$signed), "`"),
    paste0("- **Project Type & Entrypoint:** `", sanitize_markdown_inline(manifest$project$type), "` / `", sanitize_markdown_inline(ep), "`"),
    paste0("- **R Version:** `", sanitize_markdown_inline(r_ver), "` | **Toolchains:** ", sanitize_markdown_inline(tc_str)),
    paste0("- **RNG Seed & Kind:** `", seed_lbl, "` (`", sanitize_markdown_inline(paste(unlist(manifest$rng$kind), collapse = " / ")), "`)"),
    ver_lines,
    "",
    "## Option 1: Verify Locally in an Isolated R Sandbox (No Docker Required)",
    "",
    "```r",
    "library(rcapsule)",
    "audit <- verify_capsule(",
    "  manifest = \"capsule.json\",",
    "  path     = \".\",",
    "  runner   = \"sandbox\"",
    ")",
    "audit",
    "render_certificate(audit, output = \"peer_review_certificate\", format = \"both\")",
    "```",
    "",
    "## Option 2: Reproduce Inside Docker",
    "",
    "```bash",
    paste0("docker build ", plat_flag, "-t ", sanitize_slug(proj), ":repro ."),
    paste0("docker run --rm ", plat_flag, sanitize_slug(proj), ":repro"),
    "```",
    "",
    "Or using Docker Compose:",
    "",
    "```bash",
    "docker compose up --build",
    "```",
    "",
    "## Option 3: Reproduce on an HPC Cluster with Apptainer / Singularity",
    "",
    "```bash",
    "apptainer build capsule.sif Apptainer.def",
    "apptainer test capsule.sif",
    "apptainer run capsule.sif",
    "```",
    "",
    "## Bundle Contents",
    "",
    paste0("- `", sort(unique(included_files)), "`"),
    "",
    "---",
    paste0("_Generated by `rcapsule` ", as.character(utils::packageVersion("rcapsule")), "._")
  )
}

#' Export a Journal-Ready Reproducibility Supplement Bundle
#'
#' Packages container specifications (`Dockerfile`, `docker-compose.yml`,
#' `Apptainer.def`), the cryptographic provenance manifest (`capsule.json`),
#' verification certificates (`capsule_certificate.md` and `.html`), recorded
#' project inputs/scripts/outputs, and an auto-generated `README_REPRODUCE.md`
#' peer-review guide into either a clean directory or a portable ZIP archive.
#' Strictly enforces project-root path confinement and zip-slip safety so no
#' path traversal (`..`), absolute paths, or external symlinks can enter the
#' exported bundle.
#'
#' @param path Path to the project root directory. Defaults to `"."`.
#' @param output Destination path for the exported ZIP archive (when
#'   `format = "zip"`) or output directory (when `format = "dir"`).
#' @param format Export format: `"zip"` (default) or `"dir"`.
#' @param manifest Optional `rcapsule_manifest` object or path to
#'   `capsule.json`. If `NULL`, reads `file.path(path, "capsule.json")` when
#'   present or creates a fresh manifest via [create_capsule_manifest()].
#' @param verification Optional `rcapsule_verification` object from
#'   [verify_capsule()]. When supplied and `include_certificate = TRUE`,
#'   automatically renders certificates into the bundle.
#' @param certificate Optional `rcapsule_certificate` object from
#'   [render_certificate()].
#' @param include_inputs Logical; include recorded input files (default `TRUE`).
#' @param include_scripts Logical; include recorded scripts & lockfiles
#'   (default `TRUE`).
#' @param include_outputs Logical; include recorded output artifacts (default
#'   `TRUE`).
#' @param include_containers Logical; include `Dockerfile`, `docker-compose.yml`,
#'   and `Apptainer.def`, compiling any missing specs on the fly (default
#'   `TRUE`).
#' @param include_certificate Logical; include Markdown and HTML verification
#'   certificates when available (default `TRUE`).
#' @param platform Optional target container platform (`"linux/amd64"`,
#'   `"linux/arm64"`, or `NULL`) forwarded to container compilation and
#'   `README_REPRODUCE.md`.
#' @param overwrite Logical; if `FALSE` (default), aborts when `output` already
#'   exists.
#'
#' @return An S3 object of class `rcapsule_export` with fields `output_path`,
#'   `format`, `files`, `n_files`, `size_bytes`, `sha256`, and `capsule_id`.
#' @export
#' @examples
#' tmp <- tempfile("rcapsule_export_")
#' dir.create(tmp)
#' writeLines("write.csv(data.frame(x = 1:3), 'out.csv', row.names = FALSE)",
#'            file.path(tmp, "run.R"))
#' write.csv(data.frame(x = 1:3), file.path(tmp, "out.csv"), row.names = FALSE)
#' m <- create_capsule_manifest(tmp, outputs = "out.csv", seed = 1L)
#' v <- verify_capsule(m, path = tmp)
#' zip_out <- file.path(tempdir(), paste0(basename(tmp), "_supplement.zip"))
#' exp <- export_capsule_bundle(tmp, output = zip_out, manifest = m, verification = v)
#' exp
#' unlink(c(tmp, zip_out), recursive = TRUE)
export_capsule_bundle <- function(path = ".",
                                  output,
                                  format = c("zip", "dir"),
                                  manifest = NULL,
                                  verification = NULL,
                                  certificate = NULL,
                                  include_inputs = TRUE,
                                  include_scripts = TRUE,
                                  include_outputs = TRUE,
                                  include_containers = TRUE,
                                  include_certificate = TRUE,
                                  platform = NULL,
                                  overwrite = FALSE) {
  format <- match.arg(format)
  root <- normalize_project_path(path, must_exist = TRUE)
  real_root <- canonical_real_dir(root)
  platform <- validate_container_platform(platform, arg = "platform")

  if (!is.character(output) || length(output) != 1L || is.na(output) || !nzchar(output)) {
    cli::cli_abort("{.arg output} must be a non-empty file or directory path.")
  }
  assert_no_control_chars(output, arg = "output")

  out_target <- if (identical(format, "zip") && !grepl("\\.zip$", output, ignore.case = TRUE)) {
    paste0(output, ".zip")
  } else {
    output
  }

  if ((fs::file_exists(out_target) || fs::dir_exists(out_target)) && !isTRUE(overwrite)) {
    cli::cli_abort(
      "Destination {.path {out_target}} already exists. Set {.code overwrite = TRUE} to replace it."
    )
  }

  # Resolve manifest
  if (is.character(manifest) && length(manifest) == 1L) {
    manifest <- read_capsule_manifest(manifest)
  } else if (is.null(manifest)) {
    default_mf <- file.path(real_root, "capsule.json")
    if (fs::file_exists(default_mf) && is_confined_existing_path(default_mf, real_root)) {
      manifest <- read_capsule_manifest(default_mf)
    } else {
      manifest <- create_capsule_manifest(real_root)
    }
  }
  if (!inherits(manifest, "rcapsule_manifest")) {
    cli::cli_abort("{.arg manifest} must be an {.cls rcapsule_manifest} or path to capsule.json.")
  }

  # Stage inside a clean temporary directory before zipping or copying
  stage_dir <- as.character(fs::path_norm(tempfile("rcapsule_bundle_stage_")))
  fs::dir_create(stage_dir)
  on.exit(unlink(stage_dir, recursive = TRUE, force = TRUE), add = TRUE)
  real_stage <- canonical_real_dir(stage_dir)

  staged_files <- character()
  copy_confined_rel <- function(rel) {
    rel <- assert_safe_manifest_rel_path(rel, arg = "bundle entry")
    src <- assert_confined_path(rel, root = real_root, must_exist = FALSE, arg = "bundle source")
    if (!fs::file_exists(src)) {
      return(invisible(FALSE))
    }
    dst <- assert_confined_path(rel, root = real_stage, must_exist = FALSE, arg = "bundle destination")
    fs::dir_create(fs::path_dir(dst))
    fs::file_copy(src, dst, overwrite = TRUE)
    staged_files <<- unique(c(staged_files, rel))
    invisible(TRUE)
  }

  # 1. Stage manifest (capsule.json)
  write_capsule_manifest(manifest, file.path(real_stage, "capsule.json"))
  staged_files <- unique(c(staged_files, "capsule.json"))

  # 2. Stage recorded inputs, scripts, outputs
  if (isTRUE(include_inputs)) {
    for (rec in manifest$artifacts$inputs) copy_confined_rel(rec$path)
  }
  if (isTRUE(include_scripts)) {
    for (rec in manifest$artifacts$scripts) copy_confined_rel(rec$path)
  }
  if (isTRUE(include_outputs)) {
    for (rec in manifest$artifacts$outputs) copy_confined_rel(rec$path)
  }

  # 3. Stage container definitions (copy existing confined specs or compile missing ones)
  if (isTRUE(include_containers)) {
    for (rec in manifest$artifacts$containers) copy_confined_rel(rec$path)
    sc <- NULL
    ensure_scan <- function() {
      if (is.null(sc)) sc <<- scan_project(real_root)
      sc
    }
    if (!("Dockerfile" %in% staged_files)) {
      if (!isTRUE(copy_confined_rel("Dockerfile"))) {
        compile_dockerfile(ensure_scan(), output = file.path(real_stage, "Dockerfile"), platform = platform)
        staged_files <- unique(c(staged_files, "Dockerfile"))
      }
    }
    if (!("docker-compose.yml" %in% staged_files)) {
      if (!isTRUE(copy_confined_rel("docker-compose.yml"))) {
        compile_compose(ensure_scan(), output = file.path(real_stage, "docker-compose.yml"), platform = platform)
        staged_files <- unique(c(staged_files, "docker-compose.yml"))
      }
    }
    if (!any(grepl("\\.def$", staged_files, ignore.case = TRUE))) {
      if (!isTRUE(copy_confined_rel("Apptainer.def"))) {
        compile_apptainer(ensure_scan(), output = file.path(real_stage, "Apptainer.def"))
        staged_files <- unique(c(staged_files, "Apptainer.def"))
      }
    }
  }

  # 4. Stage verification certificates
  if (isTRUE(include_certificate)) {
    if (!is.null(certificate)) {
      if (!inherits(certificate, "rcapsule_certificate")) {
        cli::cli_abort("{.arg certificate} must be an {.cls rcapsule_certificate} object.")
      }
      if (!is.null(certificate$markdown)) {
        writeLines(certificate$markdown, file.path(real_stage, "capsule_certificate.md"), useBytes = TRUE)
        staged_files <- unique(c(staged_files, "capsule_certificate.md"))
      }
      if (!is.null(certificate$html)) {
        writeLines(certificate$html, file.path(real_stage, "capsule_certificate.html"), useBytes = TRUE)
        staged_files <- unique(c(staged_files, "capsule_certificate.html"))
      }
    } else if (!is.null(verification)) {
      render_certificate(
        verification,
        output = file.path(real_stage, "capsule_certificate"),
        format = "both"
      )
      staged_files <- unique(c(staged_files, "capsule_certificate.md", "capsule_certificate.html"))
    } else {
      copy_confined_rel("capsule_certificate.md")
      copy_confined_rel("capsule_certificate.html")
    }
  }

  # 5. Generate README_REPRODUCE.md
  all_bundle_files <- sort(unique(c(staged_files, "README_REPRODUCE.md")))
  readme_lines <- build_reproduce_readme(
    manifest = manifest,
    verification = verification,
    platform = platform,
    included_files = all_bundle_files
  )
  writeLines(readme_lines, file.path(real_stage, "README_REPRODUCE.md"), useBytes = TRUE)

  # Final zip-slip verification on every staged path
  for (sf in all_bundle_files) {
    assert_safe_manifest_rel_path(sf, arg = "exported bundle file")
  }

  # 6. Emit final directory or ZIP archive
  if (identical(format, "dir")) {
    if (fs::dir_exists(out_target)) {
      unlink(out_target, recursive = TRUE, force = TRUE)
    }
    fs::dir_create(out_target)
    for (rel in all_bundle_files) {
      src_f <- file.path(real_stage, rel)
      dst_f <- file.path(out_target, rel)
      fs::dir_create(fs::path_dir(dst_f))
      fs::file_copy(src_f, dst_f, overwrite = TRUE)
    }
    total_bytes <- sum(as.numeric(fs::file_size(file.path(out_target, all_bundle_files))))
    out_sha <- NA_character_
    final_path <- as.character(fs::path_norm(out_target))
  } else {
    fs::dir_create(fs::path_dir(out_target))
    if (fs::file_exists(out_target)) {
      unlink(out_target, force = TRUE)
    }
    abs_zip <- as.character(fs::path_abs(out_target))
    top_entries <- list.files(real_stage, all.files = TRUE, no.. = TRUE)
    zip::zipr(zipfile = abs_zip, files = top_entries, root = real_stage)

    # Verify zip entries are strictly zip-slip safe
    zlist <- zip::zip_list(abs_zip)$filename
    for (zf in zlist) {
      clean_zf <- sub("/$", "", zf)
      if (nzchar(clean_zf)) {
        assert_safe_manifest_rel_path(clean_zf, arg = "zip archive entry")
      }
    }
    total_bytes <- as.numeric(fs::file_size(abs_zip))
    out_sha <- sha256_file(abs_zip)
    final_path <- as.character(fs::path_norm(abs_zip))
  }

  structure(
    list(
      output_path = final_path,
      format = format,
      files = all_bundle_files,
      n_files = length(all_bundle_files),
      size_bytes = total_bytes,
      sha256 = out_sha,
      capsule_id = manifest$capsule_id
    ),
    class = "rcapsule_export"
  )
}

#' @export
print.rcapsule_export <- function(x, ...) {
  cli::cli_h1("rcapsule Exported Supplement Bundle ({x$format})")
  cli::cli_ul(c(
    "Destination: {.path {x$output_path}}",
    "Capsule ID: {.val {x$capsule_id}}",
    "Files bundled: {x$n_files} ({round(x$size_bytes / 1024, 1)} KiB)",
    "Archive SHA-256: {.val {if (!is.na(x$sha256)) short_sha(x$sha256) else '<directory>'}}"
  ))
  invisible(x)
}
