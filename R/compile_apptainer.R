# HPC-compatible Apptainer / Singularity .def recipe compiler

#' Compile an HPC-Ready Apptainer / Singularity Definition File
#'
#' Generates an Apptainer/Singularity `.def` recipe from an `rcapsule_scan`
#' (or project directory path) suitable for university and national HPC
#' clusters. Includes pinned `Bootstrap: docker` / `From:` headers, `%labels`,
#' `%files`, `%environment`, strict `set -euo pipefail` `%post` provisioning
#' for OS system libraries, scientific toolchains, and R packages, standard
#' HPC bind mount points, `%runscript`, and a `%test` verification suite.
#'
#' @param scan An `rcapsule_scan` object from [scan_project()] or a path to a
#'   project directory.
#' @param output Optional file path to write the `.def` recipe (e.g.,
#'   `"Apptainer.def"`). If `NULL`, returns the compiled spec in memory.
#' @param base_image Optional pinned Docker base image (defaults to
#'   `paste0("rocker/r-ver:", r_version)`).
#' @param r_version Optional R version string overriding `scan$r_version`.
#' @param base_digest Optional SHA-256 image digest appended to `base_image`.
#' @param cran_repo Pinned CRAN or Posit Public Package Manager repository URL.
#' @param quarto_version Pinned Quarto CLI version when Quarto is detected.
#' @param cmdstan_version Pinned CmdStan version when CmdStan is detected.
#' @param workdir Project directory inside the container image. Defaults to
#'   `"/capsule"`.
#' @param entrypoint Optional override for the `%runscript` entrypoint.
#' @param allow_unpinned Logical; if `FALSE` (default), rejects `:latest` or
#'   untagged base images.
#'
#' @return An S3 object of class `c("rcapsule_apptainer", "rcapsule_spec")`
#'   with fields `content`, `lines`, `base_image`, `r_version`, `sections`,
#'   `project_type`, `path`, `def_path`, `sif_path`, `binds`, `def_sha256`,
#'   `content_digest`, and `scan`.
#' @export
#' @examples
#' tmp <- tempfile("rcapsule_apptainer_")
#' dir.create(tmp)
#' writeLines(c("library(stats)", "cat(mean(1:10), '\\n')"), file.path(tmp, "run.R"))
#' def <- compile_apptainer(tmp)
#' cat(def$content)
#' unlink(tmp, recursive = TRUE)
compile_apptainer <- function(scan,
                              output = NULL,
                              base_image = NULL,
                              r_version = NULL,
                              base_digest = NULL,
                              cran_repo = "https://packagemanager.posit.co/cran/2026-01-15",
                              quarto_version = "1.5.57",
                              cmdstan_version = "2.35.0",
                              workdir = "/capsule",
                              entrypoint = NULL,
                              allow_unpinned = FALSE) {
  scan <- as_rcapsule_scan(scan)
  r_ver <- validate_version_string(as.character(r_version %||% scan$r_version), arg = "r_version")
  base_ref <- format_base_image_ref(base_image, r_ver, base_digest, allow_unpinned = allow_unpinned)
  validate_cran_repo_url(cran_repo, arg = "cran_repo")
  validate_version_string(quarto_version, arg = "quarto_version")
  validate_version_string(cmdstan_version, arg = "cmdstan_version")
  validate_container_workdir(workdir, arg = "workdir")

  ep <- entrypoint %||% scan$entrypoint
  if (!is.null(ep) && !identical(ep, ".")) {
    validate_safe_rel_spec_path(ep, arg = "entrypoint")
  }

  has_quarto <- tc_active(scan, "quarto")
  has_latex <- tc_active(scan, "latex")
  has_python <- tc_active(scan, "python")
  has_cmdstan <- tc_active(scan, "cmdstan")
  has_jags <- tc_active(scan, "jags")

  apt_pkgs <- unique(c(
    "ca-certificates",
    scan$sysreqs$apt_package[scan$sysreqs$stage == "build"],
    scan$sysreqs$apt_package[scan$sysreqs$stage == "runtime"]
  ))
  if (has_quarto) apt_pkgs <- unique(c(apt_pkgs, "curl"))
  apt_pkgs <- sort(apt_pkgs)

  req_r_pkgs <- validate_r_package_names(
    scan$packages$package[!scan$packages$is_base & scan$packages$required],
    arg = "scan$packages"
  )
  install_r_pkgs <- setdiff(req_r_pkgs, recommended_r_packages())

  safe_proj_comment <- sanitize_single_line_text(scan$project_name)
  safe_proj_label <- escape_apptainer_label(scan$project_name)
  rev_val <- escape_apptainer_label(scan$git$commit %||% "uncommitted")

  lines <- c(
    paste0("# Generated by rcapsule ", as.character(utils::packageVersion("rcapsule"))),
    paste0("# Project: ", safe_proj_comment, " (", scan$project_type, ") | R ", r_ver),
    "Bootstrap: docker",
    paste0("From: ", base_ref),
    "",
    "%labels",
    paste0("    Project ", safe_proj_label),
    paste0("    ProjectType ", scan$project_type),
    paste0("    RVersion ", r_ver),
    paste0("    GitRevision ", rev_val),
    paste0("    CreatedBy rcapsule-", as.character(utils::packageVersion("rcapsule"))),
    "",
    "%files",
    paste0("    . ", workdir),
    "",
    "%environment",
    "    export LC_ALL=C.UTF-8",
    "    export LANG=C.UTF-8",
    "    export TZ=UTC",
    paste0("    export CAPSULE_DIR=", workdir)
  )

  if (scan$has_renv) {
    lines <- c(
      lines,
      "    export RENV_PATHS_LIBRARY=/opt/renv/library",
      "    export R_LIBS_USER=/opt/renv/library"
    )
  }
  if (has_python) {
    lines <- c(
      lines,
      "    export VIRTUAL_ENV=/opt/venv",
      "    export RETICULATE_PYTHON=/opt/venv/bin/python",
      "    export PATH=/opt/venv/bin:$PATH"
    )
  }
  if (has_quarto) {
    lines <- c(lines, "    export PATH=/opt/quarto/bin:$PATH")
  }
  if (has_latex) {
    lines <- c(
      lines,
      "    export TINYTEX_DIR=/opt/TinyTeX",
      "    export PATH=/opt/TinyTeX/bin/x86_64-linux:/opt/TinyTeX/bin/aarch64-linux:$PATH"
    )
  }
  if (has_cmdstan) {
    lines <- c(lines, paste0("    export CMDSTAN=/opt/cmdstan/cmdstan-", cmdstan_version))
  }

  # %post
  lines <- c(
    lines,
    "",
    "%post",
    "    set -euo pipefail",
    "    export DEBIAN_FRONTEND=noninteractive",
    "    export TZ=UTC",
    paste0("    export R_REPOS=", cran_repo),
    "",
    "    # OS system dependencies",
    format_apt_run_block(apt_pkgs, prefix = "    ")
  )

  if (has_quarto) {
    lines <- c(
      lines,
      "",
      paste0("    # Quarto CLI (", quarto_version, ")"),
      "    ARCH=$(dpkg --print-architecture)",
      "    mkdir -p /opt/quarto",
      paste0(
        "    curl -fsSL \"https://github.com/quarto-dev/quarto-cli/releases/download/v",
        quarto_version, "/quarto-", quarto_version, "-linux-${ARCH}.tar.gz\" -o /tmp/quarto.tar.gz"
      ),
      "    tar -xzf /tmp/quarto.tar.gz -C /opt/quarto --strip-components=1",
      "    ln -sf /opt/quarto/bin/quarto /usr/local/bin/quarto",
      "    rm -f /tmp/quarto.tar.gz"
    )
  }

  if (has_latex) {
    lines <- c(
      lines,
      "",
      "    # TinyTeX distribution",
      "    Rscript -e \"install.packages('tinytex', repos = Sys.getenv('R_REPOS')); tinytex::install_tinytex(dir = '/opt/TinyTeX', force = TRUE)\""
    )
  }

  if (has_python) {
    lines <- c(
      lines,
      "",
      "    # Python virtual environment",
      "    python3 -m venv /opt/venv",
      "    /opt/venv/bin/pip install --no-cache-dir --upgrade pip"
    )
    has_req_txt <- "requirements.txt" %in% tolower(scan$files$path)
    if (has_req_txt) {
      req_rel <- validate_safe_rel_spec_path(
        scan$files$path[tolower(scan$files$path) == "requirements.txt"][[1L]],
        arg = "requirements.txt"
      )
      lines <- c(
        lines,
        paste0("    /opt/venv/bin/pip install --no-cache-dir -r ", workdir, "/", req_rel)
      )
    } else if (length(scan$python_packages) > 0L) {
      py_specs <- validate_python_package_specs(scan$python_packages, arg = "python_packages")
      lines <- c(
        lines,
        paste0("    /opt/venv/bin/pip install --no-cache-dir ", paste(sprintf("'%s'", py_specs), collapse = " "))
      )
    }
  }

  lines <- c(lines, "", paste0("    cd ", workdir))

  if (scan$has_renv) {
    lines <- c(
      lines,
      "    # Restore locked R packages via renv",
      "    mkdir -p /opt/renv/library",
      "    export RENV_PATHS_LIBRARY=/opt/renv/library",
      "    Rscript -e \"install.packages('renv', repos = Sys.getenv('R_REPOS')); renv::restore(prompt = FALSE)\""
    )
  } else if (scan$has_description) {
    lines <- c(
      lines,
      "    # Install DESCRIPTION dependencies",
      "    Rscript -e \"install.packages('remotes', repos = Sys.getenv('R_REPOS')); remotes::install_deps('.', dependencies = FALSE, upgrade = 'never', repos = Sys.getenv('R_REPOS'))\""
    )
    if (identical(scan$project_type, "package")) {
      lines <- c(lines, "    R CMD INSTALL --no-multiarch --with-keep.source .")
    }
  } else if (length(install_r_pkgs) > 0L) {
    pkg_vec <- paste(sprintf("'%s'", sort(unique(install_r_pkgs))), collapse = ", ")
    lines <- c(
      lines,
      "    # Install discovered R packages",
      paste0(
        "    Rscript -e \"install.packages(c(", pkg_vec,
        "), repos = Sys.getenv('R_REPOS'), Ncpus = parallel::detectCores())\""
      )
    )
  }

  if (has_cmdstan) {
    lines <- c(
      lines,
      "",
      paste0("    # CmdStan (", cmdstan_version, ")"),
      "    mkdir -p /opt/cmdstan",
      paste0(
        "    Rscript -e \"if (!requireNamespace('cmdstanr', quietly = TRUE)) install.packages('cmdstanr', repos = c('https://stan-dev.r-universe.dev', Sys.getenv('R_REPOS'))); cmdstanr::install_cmdstan(dir = '/opt/cmdstan', version = '",
        cmdstan_version, "', cores = parallel::detectCores(), quiet = FALSE)\""
      )
    )
  }

  lines <- c(
    lines,
    "",
    "    # HPC compatibility: create standard bind mount points & non-root read permissions",
    "    mkdir -p /scratch /work /data",
    paste0("    chmod -R a+rX ", workdir)
  )

  # %runscript
  run_cmd <- if (identical(scan$project_type, "shiny")) {
    paste0("    exec Rscript -e \"shiny::runApp('", workdir, "', host = '0.0.0.0', port = 3838L)\" \"$@\"")
  } else if (identical(scan$project_type, "quarto")) {
    if (isTRUE(scan$has_quarto_yml)) {
      "    exec quarto render \"$@\""
    } else {
      paste0("    exec quarto render \"", ep %||% "index.qmd", "\" \"$@\"")
    }
  } else if (identical(scan$project_type, "rmarkdown")) {
    paste0("    exec Rscript -e \"rmarkdown::render('", ep %||% "report.Rmd", "')\" \"$@\"")
  } else if (!is.null(ep) && identical(tolower(basename(ep)), "_targets.r")) {
    "    exec Rscript -e \"targets::tar_make()\" \"$@\""
  } else if (!is.null(ep)) {
    paste0("    exec Rscript \"", ep, "\" \"$@\"")
  } else {
    "    exec R \"$@\""
  }

  lines <- c(
    lines,
    "",
    "%runscript",
    paste0("    cd ", workdir),
    run_cmd
  )

  # %test
  test_lines <- c(
    "",
    "%test",
    "    set -euo pipefail",
    "    R --version"
  )
  if (length(req_r_pkgs) > 0L) {
    check_pkgs <- paste(sprintf("'%s'", sort(unique(req_r_pkgs))), collapse = ", ")
    test_lines <- c(
      test_lines,
      paste0(
        "    Rscript -e \"pkgs <- c(", check_pkgs,
        "); missing <- pkgs[!vapply(pkgs, requireNamespace, logical(1), quietly = TRUE)]; if (length(missing)) stop('Missing packages: ', paste(missing, collapse = ', '))\""
      )
    )
  }
  if (has_quarto) test_lines <- c(test_lines, "    quarto --version")
  if (has_python) test_lines <- c(test_lines, "    /opt/venv/bin/python --version")
  if (has_jags) test_lines <- c(test_lines, "    jags --version")
  if (has_cmdstan) test_lines <- c(test_lines, "    test -d \"$CMDSTAN\"")

  lines <- c(lines, test_lines)
  content <- paste0(paste(lines, collapse = "\n"), "\n")

  written_path <- NULL
  if (!is.null(output)) {
    fs::dir_create(fs::path_dir(output))
    writeLines(lines, output, useBytes = TRUE)
    written_path <- as.character(fs::path_norm(output))
  }

  def_sha <- sha256_string(content)
  sif_default <- if (!is.null(written_path)) {
    sub("\\.def$", ".sif", written_path, ignore.case = TRUE)
  } else {
    file.path(scan$project_path, paste0(sanitize_slug(scan$project_name), ".sif"))
  }

  structure(
    list(
      spec_type = "apptainer",
      content = content,
      lines = lines,
      base_image = base_ref,
      r_version = r_ver,
      sections = c("%labels", "%files", "%environment", "%post", "%runscript", "%test"),
      project_type = scan$project_type,
      path = written_path,
      def_path = written_path,
      sif_path = sif_default,
      def_sha256 = def_sha,
      content_digest = def_sha,
      binds = c("/scratch", "/work", "/data"),
      scan = scan
    ),
    class = c("rcapsule_apptainer", "rcapsule_spec")
  )
}
